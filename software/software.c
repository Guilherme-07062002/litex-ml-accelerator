bool repeating_timer_callback(struct repeating_timer *t) {
	if(cont < 3){
		ssd1306_SetCursor((cont + 4)*15, 6 + 15);
		ssd1306_WriteString(".", Font_16x15, White);
	}
	if(cont < 6 && cont > 2){
		ssd1306_SetCursor((cont + 1)*15, 6 + 15);
		ssd1306_WriteString(" ", Font_16x15, White);
	}
	if(cont > 5){
		cont = -1;
	}
	cont++;
	ssd1306_UpdateScreen();

	return true;

}

